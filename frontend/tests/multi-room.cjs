Module._load = function(request, ...args) {
  if (request === 'react-native') return { Platform: { OS: 'web' }, Share: {}, Text: element('span'), View: element('div') };
  if (request === 'expo-router') return { useRouter: () => ({ push() {}, replace() {} }) };
  if (request === '@/src/state/plan-store') return { usePlan: () => ({ state: active, geom: buildGeom(active.apartment, active.selectedRoomId), nextRoom: () => { nextCalls++; active = activateRoom(active, bedroom.id); }, reset() {} }) };
  if (request === '@/src/theme') return { makeStyles: () => () => ({}), fonts: {}, radius: {}, spacing: {} };
  if (request === '@/src/components/ui') return { money: String, Card: element('div'), Notice: ({ text }) => text, Button: props => { actions[props.testID] = props.onPress; return React.createElement('button', null, props.label); } };
  if (request === '@/src/components/WizardScaffold') return { WizardScaffold: props => { if (props.cta) actions[props.cta.testID] = props.cta.onPress; return React.createElement('main', null, props.children, props.cta?.label); } };
  if (request.startsWith('@/src/components/')) return new Proxy({}, { get: () => element('div') });
  return load.call(this, request, ...args);
};
